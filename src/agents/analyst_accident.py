"""Accident Domain Analyst Agent: analyzes retrieved accident data."""
from crewai import Agent


def create_accident_analyst(llm) -> Agent:
    return Agent(
        role="Accident Data Analyst",
        goal="วิเคราะห์ข้อมูลอุบัติเหตุที่ค้นมาได้ สังเคราะห์ประเด็นสำคัญ ระบุจุดเสี่ยง แนวโน้ม และกลุ่มเสี่ยง",
        backstory=(
            "คุณเป็นนักวิเคราะห์ข้อมูลอุบัติเหตุที่มีความเชี่ยวชาญ "
            "คุณสามารถตีความข้อมูลสถิติอุบัติเหตุ ระบุจุดเสี่ยง ช่วงเวลาเสี่ยง "
            "วิเคราะห์ปัจจัยที่เกี่ยวข้อง เช่น สภาพถนน สภาพอากาศ ประเภทยานพาหนะ "
            "และเสนอแนวทางป้องกันบนพื้นฐานหลักฐานเชิงข้อมูล "
            "คุณต้องแยก 'ข้อเท็จจริง' ออกจาก 'การตีความ' อย่างชัดเจน "
            "และห้ามสรุปเกินหลักฐานที่มี"
        ),
        llm=llm,
        verbose=True,
        allow_delegation=False,
    )


ACCIDENT_ANALYSIS_PROMPT = """
จากข้อมูลอุบัติเหตุที่ค้นมาได้ ให้วิเคราะห์และสรุปดังนี้:

1. **key_findings**: ข้อค้นพบสำคัญ (อย่างน้อย 3 ข้อ)
2. **trends**: แนวโน้มที่พบ (เพิ่มขึ้น/ลดลง/ทรงตัว)
3. **risk_areas**: พื้นที่เสี่ยงสูง
4. **risk_times**: ช่วงเวลาเสี่ยง
5. **risk_groups**: กลุ่มเสี่ยงหลัก
6. **contributing_factors**: ปัจจัยที่เกี่ยวข้อง (สภาพถนน สภาพอากาศ ฯลฯ)
7. **recommended_actions**: ข้อเสนอเชิงมาตรการ แบ่งเป็นระยะสั้น/กลาง/ยาว
8. **chart_candidates**: กราฟที่ควรมีในรายงาน (ระบุ chart_type, title, x, y)
9. **table_candidates**: ตารางที่ควรมีในรายงาน (ระบุ table_name, columns)

กฎสำคัญ:
- ถ้าไม่มีข้อมูลเชิงปริมาณ ห้ามสร้างข้อสรุปเชิงยืนยัน
- ข้อเสนอต้องอิงจากหลักฐานที่พบ
- ต้องระบุข้อจำกัดของข้อมูลที่ใช้วิเคราะห์

ใช้ข้อมูลจากขั้นตอนการค้นคืนข้อมูล (Retrieval) ที่ได้มาก่อนหน้านี้ในการวิเคราะห์
"""
