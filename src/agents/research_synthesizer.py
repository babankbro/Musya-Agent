"""Research Synthesizer Agent: expands raw data + analysis into narrative prose blocks."""
from crewai import Agent
from src.agents.agent_defaults import agent_retry_kwargs


def create_research_synthesizer(llm) -> Agent:
    return Agent(
        role="Research Synthesizer",
        goal=(
            "แปลงข้อมูลดิบ ตัวเลขสถิติ และผลการวิเคราะห์ให้เป็นย่อหน้าเล่าเรื่องที่ไหลลื่น "
            "สมบูรณ์ และพร้อมนำไปรวมในรายงานราชการภาษาไทยได้ทันที "
            "แต่ละส่วนต้องมีความยาว 300–500 คำ พร้อมบริบท การเปรียบเทียบ และนัยสำคัญ"
        ),
        backstory=(
            "คุณเป็นนักวิจัยสาธารณสุขที่เชี่ยวชาญในการสังเคราะห์ข้อมูลเชิงปริมาณ "
            "ให้เป็นเรื่องราวที่มีความหมายสำหรับผู้กำหนดนโยบาย "
            "คุณมีทักษะพิเศษในการเชื่อมโยงตัวเลขกับบริบทสังคม เศรษฐกิจ และระบบสุขภาพ "
            "คุณเขียนย่อหน้าที่มีโครงสร้าง: ประโยคนำ → หลักฐาน → การตีความ → นัยสำคัญ "
            "คุณไม่เขียนแค่ bullet points แต่สร้างเรื่องราวที่เชื่อมทุกข้อมูลเข้าด้วยกัน "
            "และอ้างอิง [C-xxx] ทุกตัวเลขสำคัญเสมอ"
        ),
        llm=llm,
        verbose=True,
        allow_delegation=False,
        max_iter=8,
        **agent_retry_kwargs(),
    )


