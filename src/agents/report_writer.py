"""Report Writer Agent: composes final Thai-language report from analysis."""
from crewai import Agent


def create_report_writer(llm) -> Agent:
    return Agent(
        role="Health Report Writer",
        goal="เรียบเรียงข้อมูลและผลการวิเคราะห์ให้เป็นรายงานภาษาไทยที่เป็นทางการ อ่านง่าย และมีการอ้างอิงแหล่งข้อมูล",
        backstory=(
            "คุณเป็นนักเขียนรายงานสุขภาพมืออาชีพ "
            "คุณสามารถเรียบเรียงข้อมูลทางสถิติและผลการวิเคราะห์ให้เป็นภาษาทางการ "
            "ที่เหมาะสำหรับแผนสุขภาพระดับจังหวัดหรือรายงานเชิงบริหาร "
            "คุณต้องแยก 'ข้อเท็จจริง' กับ 'ข้อเสนอเชิงนโยบาย' ออกจากกันอย่างชัดเจน "
            "และอ้างอิงหลักฐานในทุกข้อสรุปสำคัญ "
            "คุณเขียนเป็นภาษาไทยเสมอ ยกเว้นศัพท์เทคนิคที่จำเป็น"
        ),
        llm=llm,
        verbose=True,
        allow_delegation=False,
    )


